def plot(floor, cfg, log_dir, algos):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig_dir = 'figures_ind' 
    os.makedirs(fig_dir, exist_ok=True)
    
    for alg in algos:
        fig, ax = plt.subplots(1, 1,figsize = (6, 6))

        for lr in cfg.lrs:
            diverged_count = 0
                            
            seed_losses = []
            for sd in cfg.seeds:
                filename = log_dir + '/train_layer{}_V{}_{}_lr{}_sd{}_p{}_nheads{}.pth'.format(cfg.n_layer, cfg.vocab_size, alg, lr, sd, cfg.p_repeat, cfg.n_head)
                loaded_dict = torch.load(filename)
                hist = loaded_dict['hist_list']

                if len(hist) < cfg.steps or any(math.isnan(v) for v in hist):
                    diverged_count += 1
                    continue  # Do not include diverged runs in valid mean plot
                
                # if len(hist) < cfg.steps:
                #     hist = hist + [float('nan')] * (cfg.steps - len(hist))
                
                seed_losses.append(hist)

                total_expected_seeds = len(cfg.seeds)
                if not seed_losses or diverged_count >= (total_expected_seeds / 2):
                    print(f"Skipping plot for {alg} @ lr={lr} ({diverged_count}/{total_expected_seeds} seeds diverged)")
                    continue
                
            if not seed_losses:
                continue

            losses_np = np.array(seed_losses, dtype=np.float32)
            losses_mean = np.mean(losses_np, axis=0)
            # losses_tensor = torch.tensor(seed_losses, dtype=torch.float32)
            # losses_mean = torch.nanmean(losses_tensor, axis=0)
            # if losses_tensor.shape[0] > 1:
            #     losses_std = torch.nanstd(losses_tensor, dim=0)
            # else:
            #     losses_std = torch.zeros_like(losses_mean)

            num_valid_seeds = losses_np.shape[0]
            if num_valid_seeds > 1:
                losses_sem = np.std(losses_np, axis=0, ddof=1) / np.sqrt(num_valid_seeds)
            else:
                losses_sem = np.zeros_like(losses_mean)

            ax.plot(range(1,len(losses_mean)+1), losses_mean, lw = 3, label=f'lr={lr}')
            ax.fill_between(range(1,len(losses_mean)+1), losses_mean - losses_sem, losses_mean + losses_sem, alpha=0.15)
            #ax.fill_between(range(1,len(losses_mean)+1), losses_mean-losses_std/4, losses_mean+losses_std/4, alpha = 0.1)
        ax.axhline(floor, color='gray', linestyle='--', linewidth=1, label='entropy floor')

        ax.set_xlabel('Iteration')
        ax.tick_params(axis='both', which='major', labelsize=30, width = 3, length = 10)
        ax.tick_params(axis='both', which='minor', labelsize=20, width = 3, length = 5)
        ax.legend(fontsize=10)
        ax.spines[['right', 'top']].set_visible(False)
        ax.spines['left'].set_linewidth(3)
        ax.spines['bottom'].set_linewidth(3)
        ax.set_yscale('log')
            
        plt.tight_layout()
        plt.savefig(fig_dir + '/loss_layer{}_V{}_{}_p{}_nheads{}.pdf'.format(cfg.n_layer, cfg.vocab_size, alg, cfg.p_repeat, cfg.n_head), dpi=600)
        plt.close(fig)


