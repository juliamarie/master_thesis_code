@dataclass
class Config:
    # NOTE: this exact configuration was tuned/verified (on CPU) to reliably
    # reproduce the effect below. Two attention layers is not an arbitrary
    # choice -- it's the minimum depth an "induction head" circuit needs, so
    # don't drop n_layer below 2. Feel free to scale batch_size/steps up on a
    # T4/M3 (both run this in well under a minute); if you scale d_model or
    # n_layer up a lot, the two LRs below may need retuning, since the LR at
    # which AdamW starts to stall shifts with model width/depth.
    vocab_size: int = 24
    seq_len: int = 96
    d_model: int = 64
    n_head: int = 2
    n_layer: int = 2
    d_ff: int = 256
    batch_size: int = 64
    steps: int = 6000
    weight_decay: float = 0.02
    p_repeat: float = 0.95
    data_seed: int = 0
    seeds: List[int] = field(default_factory=lambda: [0])
    lrs: List[float] = field(default_factory=lambda: [0.2])


def make_model(cfg, device, seed=1234):
    torch.manual_seed(seed)
    model = TinyGPT(cfg.vocab_size, cfg.seq_len, cfg.d_model, cfg.n_head, cfg.n_layer, cfg.d_ff)
    return model.to(device)


def build_optimizer(name, model, lr, wd):
    # standard practice: no weight decay on biases / norms / embeddings
    decay, no_decay = [], []
    for n, p in model.named_parameters():
        (no_decay if p.ndim < 2 else decay).append(p)
    groups = [{'params': decay, 'weight_decay': wd}, {'params': no_decay, 'weight_decay': 0.0}]
    if name == 'adamw':
        return torch.optim.AdamW(groups, lr=lr, betas=(0.9, 0.95), eps=1e-8)
    elif name == 'adan':
        return Adan(groups, lr=lr, betas=(0.98, 0.92, 0.99), eps=1e-8)
    #Adan(model.parameters(), lr=lr, betas=(0.98, 0.92, 0.99), weight_decay=0.0, max_grad_norm=0.0)
    raise ValueError(name)


def run(name, lr, cfg, init_state, device, seed):
    model = make_model(cfg, device, seed=seed)
    model.load_state_dict(init_state)
    opt = build_optimizer(name, model, lr, cfg.weight_decay)

    losses = []
    diverged_at = None
    t0 = time.time()
    for step in range(cfg.steps):
        x, y = sample_batch(cfg, cfg.batch_size, device, seed=cfg.data_seed * 100_003 + step)
        logits = model(x)
        loss = F.cross_entropy(logits.reshape(-1, cfg.vocab_size), y.reshape(-1))

        if not torch.isfinite(loss):
            diverged_at = step
            losses.append(float('nan'))
            break

        opt.zero_grad(set_to_none=True)
        loss.backward()
        opt.step()
        losses.append(loss.item())

    dt = time.time() - t0
    tag = f"{name}@lr={lr:g}"
    if diverged_at is not None:
        print(f"  {tag:<16s} DIVERGED at step {diverged_at} ({dt:.1f}s)")
    else:
        print(f"  {tag:<16s} final loss {losses[-1]:.3f}  ({dt:.1f}s, {cfg.steps} steps)")
    return losses


