"""
Adan vs AdamW on a synthetic causal-LM proxy task.

This code was generated by Claude Sonnet 5 High in Sep 2026 and then modified
by M. Ulbrich, TUM and Julia Kilger inspired by code from https://github.com/chengxiang/LinearTransformer/blob/main/linear_transformer.py

It targets at demonstrating that Adan is more robust wrt increased
learning rates than AdamW.

Model: a tiny 2-layer causal Transformer (~0.1M params) trained on a
synthetic "induction" task (`... A B ... A -> B`), streamed fresh every
step (single-epoch / pretraining-style regime). Solving it requires a
genuine 2-hop attention circuit ("induction head" -- Olsson et al.),
which is why loss drops sharply once the mechanism is learned rather
than gradually via memorization, and it has a closed-form achievable
loss floor (see induction_entropy_floor). This combination -- a sharp,
learnable "phase transition" plus a hard requirement on getting enough
gradient signal through early in training -- is exactly the setting
that is known to be sensitive to optimizer choice, which is why it
works well as a small stand-in for what matters in real LM pretraining.

We run a 2x2 grid: {AdamW, Adan} x {conservative LR, aggressive LR},
both optimizers initialized from the *same* weights and fed the *same*
data stream at a given LR, with NO LR warmup -- so any gap is coming
from the optimizer's update rule itself, not from data or init luck.

USAGE
-----
    python adan_vs_adamw.py                 # full run (default sizes below)
    python adan_vs_adamw.py --quick          # tiny smoke test (seconds, CPU-ok)

Needs only: torch, matplotlib.
"""
