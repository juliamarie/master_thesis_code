# ----------------------------------------------------------------------------
# Tiny causal Transformer (GPT-style), small enough to train fast on a T4
# or an M3 Max, big enough to need real optimization (not a toy quadratic).
# ----------------------------------------------------------------------------
class CausalSelfAttention(nn.Module):
    def __init__(self, d_model, n_head):
        super().__init__()
        assert d_model % n_head == 0
        self.n_head = n_head
        self.d_head = d_model // n_head
        self.qkv = nn.Linear(d_model, 3 * d_model, bias=False)
        self.proj = nn.Linear(d_model, d_model, bias=False)

    def forward(self, x):
        B, T, C = x.shape
        qkv = self.qkv(x).view(B, T, 3, self.n_head, self.d_head).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]
        y = F.scaled_dot_product_attention(q, k, v, is_causal=True)
        y = y.transpose(1, 2).contiguous().view(B, T, C)
        return self.proj(y)


class Block(nn.Module):
    def __init__(self, d_model, n_head, d_ff):
        super().__init__()
        self.ln1 = nn.LayerNorm(d_model)
        self.attn = CausalSelfAttention(d_model, n_head)
        self.ln2 = nn.LayerNorm(d_model)
        self.mlp = nn.Sequential(nn.Linear(d_model, d_ff), nn.GELU(), nn.Linear(d_ff, d_model))

    def forward(self, x):
        x = x + self.attn(self.ln1(x))
        x = x + self.mlp(self.ln2(x))
        return x


class TinyGPT(nn.Module):
    def __init__(self, vocab_size, seq_len, d_model, n_head, n_layer, d_ff):
        super().__init__()
        self.tok_emb = nn.Embedding(vocab_size, d_model)
        self.pos_emb = nn.Embedding(seq_len, d_model)
        self.blocks = nn.ModuleList([Block(d_model, n_head, d_ff) for _ in range(n_layer)])
        self.ln_f = nn.LayerNorm(d_model)
        self.head = nn.Linear(d_model, vocab_size, bias=False)
        self.apply(self._init_weights)

    @staticmethod
    def _init_weights(m):
        if isinstance(m, nn.Linear):
            nn.init.normal_(m.weight, std=0.02)
            if m.bias is not None:
                nn.init.zeros_(m.bias)
        elif isinstance(m, nn.Embedding):
            nn.init.normal_(m.weight, std=0.02)

    def forward(self, idx):
        B, T = idx.shape
        pos = torch.arange(T, device=idx.device)
        x = self.tok_emb(idx) + self.pos_emb(pos)[None]
        for blk in self.blocks:
            x = blk(x)
        return self.head(self.ln_f(x))


def num_params(model):
    return sum(p.numel() for p in model.parameters())


# ----------------------------------------------------------------------------
# Synthetic data: an "induction" task (Olsson et al.-style: ... A B ... A -> B),
# streamed fresh every step (single-epoch / pretraining-style regime).
#
# Sequence is i.i.d. Uniform(V) EXCEPT that, at each position, with
# probability p_repeat (and only if the preceding token has appeared before
# in this sequence) the next token instead COPIES whatever token followed
# that preceding token's most recent occurrence. Solving this requires a
# genuine 2-hop attention circuit ("induction head") -- a small, well-known
# proxy for the kind of in-context structure real LMs pick up early in
# pretraining -- so loss drops sharply once the mechanism is learned, unlike
# a plain n-gram table that has to be memorized token-by-token. That sharp,
# learnable drop is what makes optimizer speed/robustness differences show
# up within a few hundred steps.
# ----------------------------------------------------------------------------
def sample_induction_batch(vocab_size, batch_size, seq_len, p_repeat, seed):
    g = torch.Generator(device='cpu').manual_seed(seed)
    tokens = torch.empty(batch_size, seq_len + 1, dtype=torch.long)
    tokens[:, 0] = torch.randint(0, vocab_size, (batch_size,), generator=g)
    next_after = torch.full((batch_size, vocab_size), -1, dtype=torch.long)
    have_data_mask = torch.zeros(batch_size, seq_len, dtype=torch.bool)

    for t in range(1, seq_len + 1):
        prev = tokens[:, t - 1]
        cur_next = next_after.gather(1, prev.unsqueeze(1)).squeeze(1)
        have_data = cur_next >= 0
        coin = torch.rand(batch_size, generator=g) < p_repeat
        do_induct = have_data & coin
        rand_tok = torch.randint(0, vocab_size, (batch_size,), generator=g)
        new_tok = torch.where(do_induct, cur_next.clamp(min=0), rand_tok)
        tokens[:, t] = new_tok
        have_data_mask[:, t - 1] = have_data
        next_after.scatter_(1, prev.unsqueeze(1), new_tok.unsqueeze(1))

    return tokens[:, :-1], tokens[:, 1:], have_data_mask


def sample_batch(cfg, batch_size, device, seed):
    x, y, _ = sample_induction_batch(cfg.vocab_size, batch_size, cfg.seq_len, cfg.p_repeat, seed)
    return x.to(device), y.to(device)


def induction_entropy_floor(cfg, n_samples=4000, seed=12345):
    """Closed-form achievable loss (nats): a mixture of 'certain copy' (when
    the induction pattern applies) and 'uniform guess' (when it doesn't),
    weighted by the empirical fraction of positions where induction applies."""
    _, _, have_data_mask = sample_induction_batch(cfg.vocab_size, n_samples, cfg.seq_len, cfg.p_repeat, seed)
    frac_have = have_data_mask.float().mean().item()
    V, p = cfg.vocab_size, cfg.p_repeat
    top_p = p + (1 - p) / V
    other_p = (1 - p) / V
    H_mix = -(top_p * math.log(top_p) + (V - 1) * other_p * math.log(other_p))
    H_uniform = math.log(V)
    return frac_have * H_mix + (1 - frac_have) * H_uniform, frac_have


