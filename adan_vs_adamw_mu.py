@dataclass
class Config:
    # NOTE: this exact configuration was tuned/verified (on CPU) to reliably
    # reproduce the effect below. Two attention layers is not an arbitrary
    # choice -- it's the minimum depth an "induction head" circuit needs, so
    # don't drop n_layer below 2. Feel free to scale batch_size/steps up on a
    # T4/M3 (both run this in well under a minute); if you scale d_model or
    # n_layer up a lot, the two LRs below may need retuning, since the LR at
    # which AdamW starts to stall shifts with model width/depth.
    vocab_size: int = 24
    seq_len: int = 96
    d_model: int = 64
    n_head: int = 2
    n_layer: int = 2
    d_ff: int = 256
    batch_size: int = 64
    steps: int = 6000
    weight_decay: float = 0.02
    p_repeat: float = 0.95
    data_seed: int = 0


def make_model(cfg, device):
    torch.manual_seed(1234)
    model = TinyGPT(cfg.vocab_size, cfg.seq_len, cfg.d_model, cfg.n_head, cfg.n_layer, cfg.d_ff)
    return model.to(device)


def build_optimizer(name, model, lr, wd):
    # standard practice: no weight decay on biases / norms / embeddings
    decay, no_decay = [], []
    for n, p in model.named_parameters():
        (no_decay if p.ndim < 2 else decay).append(p)
    groups = [{'params': decay, 'weight_decay': wd}, {'params': no_decay, 'weight_decay': 0.0}]
    if name == 'adamw':
        return torch.optim.AdamW(groups, lr=lr, betas=(0.9, 0.95), eps=1e-8)
    elif name == 'adan':
        return Adan(groups, lr=lr, betas=(0.98, 0.92, 0.99), eps=1e-8)
    #Adan(model.parameters(), lr=lr, betas=(0.98, 0.92, 0.99), weight_decay=0.0, max_grad_norm=0.0)
    raise ValueError(name)


def run(name, lr, cfg, init_state, device):
    model = make_model(cfg, device)
    model.load_state_dict(init_state)
    opt = build_optimizer(name, model, lr, cfg.weight_decay)

    losses = []
    diverged_at = None
    t0 = time.time()
    for step in range(cfg.steps):
        x, y = sample_batch(cfg, cfg.batch_size, device, seed=cfg.data_seed * 100_003 + step)
        logits = model(x)
        loss = F.cross_entropy(logits.reshape(-1, cfg.vocab_size), y.reshape(-1))

        if not torch.isfinite(loss):
            diverged_at = step
            losses.append(float('nan'))
            break

        opt.zero_grad(set_to_none=True)
        loss.backward()
        opt.step()
        losses.append(loss.item())

    dt = time.time() - t0
    tag = f"{name}@lr={lr:g}"
    if diverged_at is not None:
        print(f"  {tag:<16s} DIVERGED at step {diverged_at} ({dt:.1f}s)")
    else:
        print(f"  {tag:<16s} final loss {losses[-1]:.3f}  ({dt:.1f}s, {cfg.steps} steps)")
    return losses


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quick', action='store_true', help='tiny smoke-test sizes (CPU-friendly, seconds)')
    ap.add_argument('--lr-mild', type=float, default=6e-3)
    ap.add_argument('--lr-aggressive', type=float, default=3e-2)
    ap.add_argument('--out', type=str, default='adan_vs_adamw_adanimpl2.png')
    args = ap.parse_args()

    device = 'cuda' if torch.cuda.is_available() else ('mps' if torch.backends.mps.is_available() else 'cpu')
    print(f"device: {device}")

    cfg = Config()
    if args.quick:
        cfg = Config(vocab_size=16, seq_len=16, d_model=32, n_head=2, n_layer=2, d_ff=64,
                     batch_size=8, steps=8)

    floor, frac_have = induction_entropy_floor(cfg, n_samples=(500 if args.quick else 4000))
    print(f"synthetic induction task: vocab={cfg.vocab_size}, p_repeat={cfg.p_repeat}, "
          f"induction-applicable positions={frac_have*100:.0f}%")
    print(f"achievable loss floor = {floor:.3f} nats (uniform baseline = {math.log(cfg.vocab_size):.3f} nats)")

    ref_model = make_model(cfg, 'cpu')
    print(f"model params: {num_params(ref_model)/1e6:.2f}M")
    init_state = {k: v.clone() for k, v in ref_model.state_dict().items()}

    results = {}
    for lr_name, lr in [('mild', args.lr_mild), ('aggressive', args.lr_aggressive)]:
        print(f"\n-- LR regime '{lr_name}' (lr={lr:g}), no warmup --")
        for opt_name in ['adamw', 'adan']:
            results[(opt_name, lr_name)] = run(opt_name, lr, cfg, init_state, device)

    plot(results, floor, args.lr_mild, args.lr_aggressive, cfg, args.out)


def plot(results, floor, lr_mild, lr_aggressive, cfg, out_path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), sharey=True)
    colors = {'adamw': 'tab:blue', 'adan': 'tab:red'}
    titles = {'mild': f'conservative LR = {lr_mild:g}', 'aggressive': f'aggressive LR = {lr_aggressive:g}  (10x, no warmup)'}

    for ax, lr_name in zip(axes, ['mild', 'aggressive']):
        for opt_name in ['adamw', 'adan']:
            y = results[(opt_name, lr_name)]
            ax.plot(range(1, len(y) + 1), y, label=opt_name, color=colors[opt_name], linewidth=1.6)
        ax.axhline(floor, color='gray', linestyle='--', linewidth=1, label='entropy floor')
        ax.set_yscale('log')
        ax.set_xlabel('training step')
        ax.set_title(titles[lr_name])
        ax.grid(alpha=0.3)
    axes[0].set_ylabel('cross-entropy loss (nats, log scale)')
    axes[0].legend()
    fig.suptitle('Adan vs AdamW on a synthetic causal-LM proxy task (no LR warmup)')
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    print(f"\nsaved plot to {out_path}")


if __name__ == '__main__':
    main()
