"""
Condense the raw run logs into two compact .npz files used by analyze.py.

This code was generated by Claude Opus 5.5 (claude-opus-5-5) in Oct 2026 edited by Julia Kilger.

  analysis/lt_curves.npz   linear transformer (log_lineartransformers/):
      test loss on a fixed eval batch (seed 99, B=1000 -- same as plot_loss_lr.py)
      every `STRIDE` iterations. shape [mode, alg, lr, seed, T]
  analysis/ind_curves.npz  induction heads (log_inductionhead/):
      per-step training loss, NaN-padded after divergence.
      shape [p, n_head, n_layer, alg, lr, seed, steps]
  analysis/ind_floors.npy  induction heads: achievable loss (entropy floor) per p_repeat,
      from induction_entropy_floor() in inductionhead_train.py. shape [p]

Run once (needs the GPU for the linear transformer part, ~25 minutes):
    .venv/Scripts/python.exe analysis/extract.py           # everything
    .venv/Scripts/python.exe analysis/extract.py ind       # only induction (curves + floors)
    .venv/Scripts/python.exe analysis/extract.py lt        # only linear transformer
"""
import os
import sys
import math

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from linear_transformer import Transformer_F, generate_data, in_context_loss  # noqa: E402
from inductionhead_train import Config, induction_entropy_floor  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'analysis')
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

# ---------------------------------------------------------------- linear transformer
LT = dict(
    modes=['normal', 'sphere', 'gamma'],
    algs=['sgd', 'adam', 'adan'],
    lrs=[1e-4, 2e-4, 5e-4, 1e-3, 2e-3, 5e-3, 1e-2, 2e-2, 5e-2, 0.1, 0.2, 0.5],
    seeds=[0, 1, 2, 3, 4, 5],
    n_layer=3, N=20, d=5, B=1000, var=0.05, shape_k=0.1, max_iters=10000,
)
STRIDE = 50


def extract_lt():
    c = LT
    T = c['max_iters'] // STRIDE
    out = np.full((len(c['modes']), len(c['algs']), len(c['lrs']), len(c['seeds']), T), np.nan, np.float32)
    model = Transformer_F(c['n_layer'], 1, c['d'], c['var']).to(device)
    for im, mode in enumerate(c['modes']):
        np.random.seed(99)
        torch.manual_seed(99)
        Z, y = generate_data(mode, c['N'], c['d'], c['B'], c['shape_k'])
        for ia, alg in enumerate(c['algs']):
            for il, lr in enumerate(c['lrs']):
                for isd, sd in enumerate(c['seeds']):
                    fn = os.path.join(ROOT, 'log_lineartransformers', f"train_layer{c['n_layer']}_N{c['N']}_{mode}_{alg}_True_lr{lr}_sd{sd}.pth")
                    if not os.path.exists(fn):
                        print('missing', fn)
                        continue
                    hist = torch.load(fn, map_location=device)['hist_list']
                    with torch.no_grad():
                        for t in range(0, c['max_iters'], STRIDE):
                            model.allparam.copy_(hist[t])
                            out[im, ia, il, isd, t // STRIDE] = in_context_loss(model, Z, y).item()
                print(f'lt {mode} {alg} lr={lr} done', flush=True)
    np.savez_compressed(os.path.join(OUT, 'lt_curves.npz'), loss=out, stride=STRIDE,
                        modes=c['modes'], algs=c['algs'], lrs=c['lrs'], seeds=c['seeds'])


# ---------------------------------------------------------------- induction heads
IND = dict(
    ps=[0.5, 0.8, 0.95],
    heads=[1, 2, 4, 8],
    layers=[2, 4, 5],
    algs=['adamw', 'adan'],
    lrs=[1e-4, 2e-4, 5e-4, 1e-3, 2e-3, 5e-3, 1e-2, 2e-2, 5e-2, 0.1, 0.2, 0.5],
    seeds=[0, 1, 2, 3, 4, 5],
    V=24, steps=6000,
)


def extract_ind():
    c = IND
    shape = (len(c['ps']), len(c['heads']), len(c['layers']), len(c['algs']), len(c['lrs']), len(c['seeds']), c['steps'])
    out = np.full(shape, np.nan, np.float32)
    for ip, p in enumerate(c['ps']):
        for ih, h in enumerate(c['heads']):
            for iL, L in enumerate(c['layers']):
                for ia, alg in enumerate(c['algs']):
                    for il, lr in enumerate(c['lrs']):
                        for isd, sd in enumerate(c['seeds']):
                            fn = os.path.join(ROOT, 'log_inductionhead',
                                              f"train_layer{L}_V{c['V']}_{alg}_lr{lr}_sd{sd}_p{p}_nheads{h}.pth")
                            if not os.path.exists(fn):
                                print('missing', fn)
                                continue
                            hist = np.asarray(torch.load(fn)['hist_list'], np.float32)
                            out[ip, ih, iL, ia, il, isd, :len(hist)] = hist
        print(f'ind p={p} done', flush=True)
    extract_ind_floors()
    np.savez_compressed(os.path.join(OUT, 'ind_curves.npz'), loss=out,
                        **{k: np.asarray(v) for k, v in c.items() if isinstance(v, list)})


def extract_ind_floors():
    # same sequence length / sample count / seed as used for the floor lines in inductionhead_train.py
    floors = []
    for p in IND['ps']:
        cfg = Config(vocab_size=IND['V'], p_repeat=p)
        floors.append(induction_entropy_floor(cfg, n_samples=4000)[0])
        print(f'ind floor p={p}: {floors[-1]:.4f} nats', flush=True)
    np.save(os.path.join(OUT, 'ind_floors.npy'), np.array(floors))


if __name__ == '__main__':
    which = sys.argv[1:] or ['ind', 'lt']
    if 'ind' in which:
        extract_ind()
    if 'lt' in which:
        extract_lt()
