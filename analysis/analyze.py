def linear_transformer():
    path = os.path.join(A, 'lt_curves.npz')
    if not os.path.exists(path):
        print('lt_curves.npz missing -- run extract.py lt first')
        return
    d = np.load(path)
    L, lrs, algs, modes = d['loss'], d['lrs'].astype(float), list(d['algs']), list(d['modes'])
    T = L.shape[-1]
    nonfinite = ~np.isfinite(L).all(-1)
    fin = np.mean(L[..., -int(FINAL_FRAC * T):], axis=-1)
    fin[nonfinite | ~np.isfinite(fin)] = np.inf
    # no stopping criterion in train.py, so many blown-up runs stay finite (1e5 .. 1e26):
    # count a run as diverged if it ends worse than it started
    div = nonfinite | (fin > L[..., 0])
    med = np.median(fin, axis=-1)                     # [mode, alg, lr]

    print('\n=== LINEAR TRANSFORMER (3 layers, N=20, d=5; test loss on fixed eval batch) ===')
    for im, mode in enumerate(modes):
        best_all = np.min(med[im])
        print(f'-- {mode}: best overall median final loss {best_all:.2e}')
        for ia, alg in enumerate(algs):
            b = np.argmin(med[im, ia])
            within = [int((med[im, ia] <= f * best_all).sum()) for f in (1.5, 2, 5)]
            print(f'   {NAME[alg]:11s} best {med[im, ia, b]:.2e} @ lr={lrs[b]:<7g} | #LRs within x1.5/x2/x5 of best-overall: '
                  f'{within}')
        ia_w, ia_n = algs.index('adam'), algs.index('adan')
        xa = fin[im, ia_w, np.argmin(med[im, ia_w])]
        xb = fin[im, ia_n, np.argmin(med[im, ia_n])]
        print(f'   AdamW vs Adan at their best LR: Welch p = {stats.ttest_ind(np.log(xa), np.log(xb), equal_var=False).pvalue:.3f}')
        print(f'   diverged seeds (final loss > initial loss, or non-finite); "non-finite" = the NaN/inf subset:')
        print_failures(lrs, algs, {'diverged': div[im], 'non-finite': nonfinite[im]}, div.shape[-1])

    # ---- Fig 4: LR sweeps per data distribution
    fig, axes = plt.subplots(1, len(modes), figsize=(12, 3.8))
    for im, mode in enumerate(modes):
        sweep_panel(axes[im], lrs, fin[im], algs, div[im])
        axes[im].set_ylim(top=min(axes[im].get_ylim()[1], 10.0))   # diverged runs would squash the plot
        axes[im].set_title(f'{mode} covariates', fontsize=10)
        axes[im].set_xlabel('learning rate')
    axes[0].set_ylabel(f'final test loss (last {int(FINAL_FRAC * 100)}%)')
    axes[0].legend(loc='upper left')
    #fig.suptitle('Linear transformer (in-context linear regression): final loss vs LR  '
                 #'(median of 6 seeds, band = min-max, ★ = best LR, n× = diverged seeds)', fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'lt_lr_sweep.pdf'))
    fig.savefig(os.path.join(FIG, 'lt_lr_sweep.png'), dpi=130)
    plt.close(fig)

    # ---- Fig 5: curves at each optimizer's best LR (the fair "who is better" comparison)
    stride = int(d['stride'])
    x = np.arange(T) * stride
    fig, axes = plt.subplots(1, len(modes), figsize=(12, 3.6))
    for im, mode in enumerate(modes):
        ax = axes[im]
        for ia, alg in enumerate(algs):
            b = np.argmin(med[im, ia])
            c = L[im, ia, b]
            ax.plot(x, np.median(c, 0), color=COL[alg], lw=1.6, label=f'{NAME[alg]} (lr={lrs[b]:g})')
            ax.fill_between(x, c.min(0), c.max(0), color=COL[alg], alpha=0.15, lw=0)
        ax.set_yscale('log')
        ax.set_title(f'{mode} covariates', fontsize=10)
        ax.set_xlabel('iteration')
        ax.legend(fontsize=8)
    axes[0].set_ylabel('test loss')
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'lt_best_lr_curves.pdf'))
    fig.savefig(os.path.join(FIG, 'lt_best_lr_curves.png'), dpi=130)
    plt.close(fig)


# =============================================================== speed (steps to reach a target loss)
# Each optimizer is compared at the LR that is FASTEST for it (median over seeds), i.e. tuned for speed.
# Diverged runs (same definitions as above) never count as having reached a target, even if they
# touched it before blowing up.
SPEED_TAUS = [0.5, 0.2, 0.05]   # induction targets: normalised excess loss (early / middle / late in training)


def first_hit(curve, target, offset):
    """curve: [..., T] smoothed loss, target broadcastable to curve[..., 0]. Index of first value <= target
    (+ offset for the smoothing window), inf if never reached."""
    hit = curve <= np.asarray(target)[..., None]
    return np.where(hit.any(-1), hit.argmax(-1) + offset, np.inf)


def induction_speed():
    d = np.load(os.path.join(A, 'ind_curves.npz'))
    L, lrs, algs = d['loss'], d['lrs'].astype(float), list(d['algs'])
    ps, heads, layers = d['ps'], d['heads'], d['layers']
    floors = np.load(os.path.join(A, 'ind_floors.npy'))
    unif = math.log(24)
    k = 100                                              # moving average over 100 steps of training loss
    cs = np.cumsum(np.nan_to_num(L, nan=1e6).astype(np.float64), axis=-1)  # NaN (diverged) never hits
    ma = (cs[..., k:] - cs[..., :-k]) / k
    del cs
    div = np.isnan(L[..., -1])

    print('\n=== INDUCTION: SPEED (steps until the 100-step moving average reaches the target) ===')
    res = {}
    for tau in SPEED_TAUS:
        target = floors + tau * (unif - floors)          # per p
        t = first_hit(ma, target[:, None, None, None, None, None], k)   # [p,h,L,alg,lr,seed]
        t[div] = np.inf
        med_t = np.median(t, axis=-1)                    # [p,h,L,alg,lr]
        fastest = med_t.min(-1)                          # [p,h,L,alg]
        res[tau] = (med_t, fastest)
        a, b = fastest[..., 0].ravel(), fastest[..., 1].ravel()
        both = np.isfinite(a) & np.isfinite(b)
        ratio = np.exp(np.mean(np.log(b[both] / a[both])))
        print(f'target = floor + {tau:.0%} of gap: Adan faster in {(b < a).sum()}/{a.size}, AdamW faster in {(a < b).sum()}, '
              f'tie {(a == b).sum()} | steps Adan/AdamW = x{ratio:.2f} (geo-mean, {both.sum()} settings) | '
              f'never reached: AdamW {np.isinf(a).sum()}, Adan {np.isinf(b).sum()}')

    # ---- Fig: AdamW vs Adan fastest time, one point per setting, one panel per target
    cap = L.shape[-1] * 1.15                             # where "never reached" is drawn
    pcol = ['#1baf7a', '#eda100', '#e87ba4']             # categorical slots 3-5 (slots 1-2 = optimizers)
    marks = ['o', 's', '^']
    hsize = np.array([22, 42, 72, 120])[:len(heads)]     # marker area grows with the number of heads
    fig, axes = plt.subplots(1, len(SPEED_TAUS), figsize=(13, 4.4))
    for ax, tau in zip(axes, SPEED_TAUS):
        fastest = res[tau][1]
        for ip, p in enumerate(ps):
            for iL, Ly in enumerate(layers):
                x = np.minimum(fastest[ip, :, iL, 0], cap)
                y = np.minimum(fastest[ip, :, iL, 1], cap)
                ax.scatter(x, y, color=pcol[ip], marker=marks[iL], s=hsize, edgecolor='white', lw=0.8, zorder=3,
                           alpha=0.9)
        lo = 100
        ax.plot([lo, cap], [lo, cap], color='0.5', lw=0.9, ls='--')
        ax.axhline(cap, color='0.8', lw=0.8)
        ax.axvline(cap, color='0.8', lw=0.8)
        ax.set_xscale('log')
        ax.set_yscale('log')
        ax.set_xlim(lo, cap * 1.1)
        ax.set_ylim(lo, cap * 1.1)
        ax.set_aspect('equal')
        ax.set_xlabel('AdamW: steps (fastest LR)')
        ax.set_title(f'target: floor + {tau:.0%} of gap', fontsize=10)
        ax.text(0.04, 0.96, 'Adan slower', transform=ax.transAxes, va='top', fontsize=8, color='0.4')
        ax.text(0.96, 0.04, 'Adan faster', transform=ax.transAxes, ha='right', fontsize=8, color='0.4')
    axes[0].set_ylabel('Adan: steps (fastest LR)')
    from matplotlib.lines import Line2D
    combo = [Line2D([], [], ls='none', marker=marks[iL], color=pcol[ip], mec='white', ms=7, label=f'p={p}, {Ly} layers')
             for ip, p in enumerate(ps) for iL, Ly in enumerate(layers)]
    sizes = [Line2D([], [], ls='none', marker='o', color='0.45', mec='white', ms=np.sqrt(sz), label=f'{h} head' + ('s' if h > 1 else ''))
             for h, sz in zip(heads, hsize)]
    leg1 = axes[-1].legend(handles=combo, fontsize=7, loc='upper left', bbox_to_anchor=(1.02, 1.0))
    axes[-1].add_artist(leg1)
    axes[-1].legend(handles=sizes, fontsize=7, loc='lower left', bbox_to_anchor=(1.02, 0.0), title='marker size',
                    title_fontsize=7)
    # fig.suptitle('Induction: steps to reach a target loss, each optimizer at its fastest LR '
    #              '(one point per setting, median of 6 seeds; grey lines = never reached)', fontsize=10)
    fig.tight_layout(rect=(0, 0, 0.87, 1))   # room for the two legends on the right
    fig.savefig(os.path.join(FIG, 'ind_speed_scatter.pdf'))
    fig.savefig(os.path.join(FIG, 'ind_speed_scatter.png'), dpi=130)
    plt.close(fig)

    # ---- Fig: steps-to-target vs LR (target 5%), same layout as the LR sweeps
    med_t = res[0.05][0]
    for ip, p in enumerate(ps):
        fig, axes = plt.subplots(len(layers), len(heads), figsize=(12, 7.5), sharex=True, sharey=True)
        for iL, Ly in enumerate(layers):
            for ih, h in enumerate(heads):
                ax = axes[iL, ih]
                for ia, alg in enumerate(algs):
                    m = med_t[ip, ih, iL, ia]
                    ok = np.isfinite(m)
                    ax.plot(lrs[ok], m[ok], '-o', color=COL[alg], lw=2, ms=4, label=NAME[alg])
                    if ok.any():
                        b = np.argmin(m)
                        ax.plot(lrs[b], m[b], '*', color=COL[alg], ms=11, mec='white', mew=0.8, zorder=5)
                ax.set_xscale('log')
                if h==1:
                    ax.set_title(f'{Ly} layers, {h} head', fontsize=9)
                else:
                    ax.set_title(f'{Ly} layers, {h} heads', fontsize=9)
                if iL == len(layers) - 1:
                    ax.set_xlabel('learning rate')
                if ih == 0:
                    ax.set_ylabel('steps to target')
        axes[0, 0].legend(loc='upper right')
        fig.suptitle(f'Induction task, p_repeat={p}: steps until loss ≤ floor + 5% of gap  '
                     f'(median of 6 seeds, ★ = fastest LR, missing point = target not reached)', fontsize=10)
        fig.tight_layout()
        fig.savefig(os.path.join(FIG, f'ind_speed_vs_lr_p{p}.pdf'))
        fig.savefig(os.path.join(FIG, f'ind_speed_vs_lr_p{p}.png'), dpi=130)
        plt.close(fig)


def linear_transformer_speed():
    path = os.path.join(A, 'lt_curves.npz')
    if not os.path.exists(path):
        return
    d = np.load(path)
    L, lrs, algs, modes = d['loss'], d['lrs'].astype(float), list(d['algs']), list(d['modes'])
    stride = int(d['stride'])
    T = L.shape[-1]
    w = 5                                                # rolling median over 5 checkpoints (250 its), robust to spikes
    Lf = np.where(np.isfinite(L), L, np.inf)
    sm = np.median(np.lib.stride_tricks.sliding_window_view(Lf, w, axis=-1), axis=-1)   # [..., T-w+1]
    fin = np.mean(Lf[..., -int(FINAL_FRAC * T):], axis=-1)
    best_all = np.min(np.median(fin, axis=-1).reshape(len(modes), -1), axis=-1)          # per mode
    div = ~np.isfinite(L).all(-1) | (fin > L[..., 0])                                    # as in linear_transformer()

    print('\n=== LINEAR TRANSFORMER: SPEED (iterations until the smoothed test loss reaches k x best final loss) ===')
    fig, axes = plt.subplots(1, len(modes), figsize=(12, 3.8))
    # second figure: same profile with markers + which LR was picked for every target
    fig2, axes2 = plt.subplots(1 + len(algs), len(modes), figsize=(12, 10), sharex='col',
                               gridspec_kw={'height_ratios': [1.6] + [1] * len(algs)})
    for im, mode in enumerate(modes):
        init = np.median(L[im, ..., 0])
        factors = np.geomspace(1.2, init / best_all[im], 40)
        prof = np.full((len(algs), len(factors)), np.inf)
        picked = np.zeros((len(algs), len(factors), len(lrs)), bool)   # all LRs tied for fastest
        for j, f in enumerate(factors):
            t = first_hit(sm[im], f * best_all[im], w - 1) * stride   # [alg, lr, seed]
            t[div[im]] = np.inf
            med_t = np.median(t, axis=-1)
            prof[:, j] = med_t.min(-1)                           # fastest LR per optimizer
            picked[:, j] = (med_t == prof[:, j, None]) & np.isfinite(med_t)
        x = factors * best_all[im]
        ax = axes2[0, im]
        for ia, alg in enumerate(algs):
            ok = np.isfinite(prof[ia])
            ax.plot(x[ok], prof[ia, ok], '-o', color=COL[alg], lw=1.2, ms=3.5, label=NAME[alg])
            axl = axes2[1 + ia, im]
            jj, ll = np.nonzero(picked[ia])
            axl.scatter(x[jj], lrs[ll], color=COL[alg], s=14, zorder=3)
            axl.set_yscale('log')
            axl.set_ylim(lrs[0] / 1.6, lrs[-1] * 1.6)
            axl.set_yticks(lrs, [f'{v:g}' for v in lrs], fontsize=7)
            axl.minorticks_off()
            if im == 0:
                axl.set_ylabel(f'{NAME[alg]}\nfastest LR')
        ax.set_yscale('log')
        ax.set_title(f'{mode} covariates', fontsize=10)
        for a in axes2[:, im]:
            a.set_xscale('log')
        axes2[0, im].invert_xaxis()
        axes2[-1, im].set_xlabel('test loss')
        for ia, alg in enumerate(algs):
            ok = np.isfinite(prof[ia])
            axes[im].plot(factors[ok] * best_all[im], prof[ia, ok], color=COL[alg], lw=2, label=NAME[alg])
        axes[im].set_xscale('log')
        axes[im].set_yscale('log')
        axes[im].invert_xaxis()
        axes[im].set_title(f'{mode} covariates', fontsize=10)
        axes[im].set_xlabel('test loss')
        print(f'-- {mode} (best final loss {best_all[im]:.2e})')
        for f in (100, 10, 2):
            if f * best_all[im] >= init:
                continue
            t = first_hit(sm[im], f * best_all[im], w - 1) * stride
            t[div[im]] = np.inf
            med_t = np.median(t, axis=-1)
            s = []
            for ia, alg in enumerate(algs):
                b = np.argmin(med_t[ia])
                s.append(f'{NAME[alg]} {med_t[ia, b]:>6.0f} @ lr={lrs[b]:<6g}' if np.isfinite(med_t[ia, b])
                         else f'{NAME[alg]}  never           ')
            print(f'   target {f:>3}x best: ' + ' | '.join(s))
    axes[0].set_ylabel('iterations')
    axes[0].legend()
    
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'lt_speed_profile.pdf'))
    fig.savefig(os.path.join(FIG, 'lt_speed_profile.png'), dpi=130)
    plt.close(fig)
    axes2[0, 0].set_ylabel('iterations to target')
    axes2[0, 0].legend(fontsize=8)
    fig2.suptitle('Linear transformer: speed profile (top; dots = the 40 targets) and the LR picked as fastest for each '
                  'target (below; several dots = tie)', fontsize=10)
    fig2.tight_layout()
    fig2.savefig(os.path.join(FIG, 'lt_speed_profile_lrs.pdf'))
    fig2.savefig(os.path.join(FIG, 'lt_speed_profile_lrs.png'), dpi=130)
    plt.close(fig2)


