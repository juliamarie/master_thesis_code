COL = {'adamw': '#2a78d6', 'adam': '#2a78d6', 'adan': '#eb6834', 'sgd': '#1baf7a'}
NAME = {'adamw': 'AdamW', 'adam': 'AdamW', 'adan': 'Adan', 'sgd': 'SGD (mom.)'}
plt.rcParams.update({'font.size': 10, 'axes.spines.right': False, 'axes.spines.top': False,
                     'axes.grid': True, 'grid.color': '0.9', 'grid.linewidth': 0.6,
                     'axes.axisbelow': True, 'legend.frameon': False, 'pdf.fonttype': 42})
FINAL_FRAC = 0.1   # final loss = mean over the last 10% of training
FAIL_GAP = 0.5     # induction: 'failed to learn' if normalised excess loss over the floor is above this


def sweep_panel(ax, lrs, fin, algs, div, floor=None, ylog=True, failed=None):
    """fin: [alg, lr, seed] final losses (inf = non-finite). div / failed: [alg, lr, seed] diverged /
    failed-to-learn runs. Median line + min/max band over seeds. Counts at the top of the panel, one row
    per optimizer and category: n† = diverged seeds, n× = failed-to-learn seeds."""
    cats = [(div, '†')] + ([(failed, '×')] if failed is not None else [])
    row = 0
    for mask, sym in cats:
        for ia, alg in enumerate(algs):
            n_runs = mask[ia].sum(-1)
            if not n_runs.any():
                continue
            for x, n in zip(lrs, n_runs):
                if n:
                    ax.annotate(f'{n}{sym}', (x, 0.99 - 0.065 * row), xycoords=('data', 'axes fraction'),
                                color=COL[alg], ha='center', va='top', fontsize=6.5,
                                bbox=dict(fc='white', ec='none', pad=0.4, alpha=0.85))
            row += 1
    for ia, alg in enumerate(algs):
        f = fin[ia]
        med = np.median(f, axis=-1)
        lo, hi = np.min(f, axis=-1), np.max(f, axis=-1)
        ok = np.isfinite(med)
        ax.fill_between(lrs[ok], lo[ok], np.where(np.isfinite(hi), hi, np.nan)[ok], color=COL[alg], alpha=0.15, lw=0)
        ax.plot(lrs[ok], med[ok], '-o', color=COL[alg], lw=2, ms=4, label=NAME[alg])
        b = np.nanargmin(np.where(ok, med, np.nan))
        ax.plot(lrs[b], med[b], '*', color=COL[alg], ms=11, mec='white', mew=0.8, zorder=5)
    if floor is not None:
        ax.axhline(floor, color='0.5', ls='--', lw=0.9)
    ax.set_xscale('log')
    if ylog:
        ax.set_yscale('log')


def print_failures(lrs, algs, counts, total):
    """counts: {label: bool array [..., alg, lr, seed]} -> per optimizer and LR, #runs in each category."""
    print(f'{"":13s}lr: ' + ' '.join(f'{x:>6g}' for x in lrs))
    for ia, alg in enumerate(algs):
        for label, c in counts.items():
            n = c[..., ia, :, :].sum(axis=tuple(range(c.ndim - 3)) + (-1,))
            print(f'   {NAME[alg]:6s} {label:9s}' + ' '.join(f'{v:6d}' for v in n) + f'   (of {total} runs per LR)')


# =============================================================== induction heads
def induction():
    d = np.load(os.path.join(A, 'ind_curves.npz'))
    L, lrs, algs = d['loss'], d['lrs'].astype(float), list(d['algs'])
    ps, heads, layers = d['ps'], d['heads'], d['layers']
    floors = np.load(os.path.join(A, 'ind_floors.npy'))
    unif = math.log(int(24))
    steps = L.shape[-1]
    div = np.isnan(L[..., -1])
    fin = np.nanmean(L[..., -int(FINAL_FRAC * steps):], axis=-1)
    fin[div] = np.inf
    # normalised excess loss: 0 = entropy floor, 1 = uniform guessing
    gap = (fin - floors[:, None, None, None, None, None]) / (unif - floors[:, None, None, None, None, None])
    med = np.median(gap, axis=-1)                                     # [p,h,L,alg,lr]
    failed = ~div & (gap > FAIL_GAP)                                  # stable but never learned the task

    print('\n=== INDUCTION HEADS ===')
    print(f'{"p":>5}{"L":>3}{"h":>3} | {"AdamW best":>17} | {"Adan best":>17} | {"diff (adan-adamw)":>18} | Welch p | #LR<=5% gap (AdamW/Adan)')
    rows = []
    for ip, p in enumerate(ps):
        for iL, Ly in enumerate(layers):
            for ih, h in enumerate(heads):
                ba = [np.nanargmin(med[ip, ih, iL, ia]) for ia in range(2)]
                xa, xb = (fin[ip, ih, iL, ia, ba[ia]] for ia in range(2))
                pv = stats.ttest_ind(xa, xb, equal_var=False).pvalue
                good = (med[ip, ih, iL] <= 0.05).sum(-1)
                rows.append((p, Ly, h, np.median(xa), np.median(xb), pv, *good))
                print(f'{p:5}{Ly:3}{h:3} | {np.median(xa):.3f} @ lr={lrs[ba[0]]:<7g}| {np.median(xb):.3f} @ lr={lrs[ba[1]]:<7g}| '
                      f'{np.median(xb) - np.median(xa):+18.3f} | {pv:7.3f} | {good[0]:2d} / {good[1]:2d}')
    rows = np.array(rows, float)
    print(f'Adan lower tuned loss in {(rows[:, 4] < rows[:, 3]).sum()}/{len(rows)} settings; '
          f'significant (p<0.05) differences: {(rows[:, 5] < 0.05).sum()}')
    print(f'total #good LRs  AdamW={int(rows[:, 6].sum())}  Adan={int(rows[:, 7].sum())}')
    shift = []
    for ip in range(len(ps)):
        for ih in range(len(heads)):
            for iL in range(len(layers)):
                g = med[ip, ih, iL] <= 0.05
                if g.all(axis=-1).any() or not g.any(axis=-1).all():
                    continue
                c = [np.mean(np.log10(lrs[g[ia]])) for ia in range(2)]  # centre of good window
                shift.append(c[1] - c[0])
    print(f'centre of good-LR window: Adan / AdamW = x{10 ** np.mean(shift):.2f} (geo-mean over settings)')
    print(f'\nfailed runs, summed over all {len(ps) * len(heads) * len(layers)} settings '
          f'(diverged = non-finite loss; failed = stable but excess loss > {FAIL_GAP} of the gap):')
    print_failures(lrs, algs, {'diverged': div, 'failed': failed}, div[..., 0, 0, :].size)

    # ---- Fig 1: LR sweeps, one figure per p (rows = layers, cols = heads)
    for ip, p in enumerate(ps):
        fig, axes = plt.subplots(len(layers), len(heads), figsize=(12, 7.5), sharex=True, sharey=True)
        for iL, Ly in enumerate(layers):
            for ih, h in enumerate(heads):
                ax = axes[iL, ih]
                sweep_panel(ax, lrs, fin[ip, ih, iL], algs, div[ip, ih, iL], floor=floors[ip],
                            failed=failed[ip, ih, iL])
                if h==1:
                    ax.set_title(f'{Ly} layers, {h} head', fontsize=9)
                else:
                    ax.set_title(f'{Ly} layers, {h} heads', fontsize=9)
                if iL == len(layers) - 1:
                    ax.set_xlabel('learning rate')
                if ih == 0:
                    ax.set_ylabel(f'final loss (last {int(FINAL_FRAC * 100)}%)')
        # headroom above the data for the count labels (up to 4 rows)
        f_ok = fin[ip][np.isfinite(fin[ip])]
        lmin, lmax = np.log(min(f_ok.min(), floors[ip])), np.log(f_ok.max())
        span = lmax - lmin
        axes[0, 0].set_ylim(np.exp(lmin - 0.05 * span), np.exp(lmax + 0.7 * span))
        # values stay within ~0.7..10: a few round ticks with plain labels instead of 3×10^0-style ones
        lo_y, hi_y = axes[0, 0].get_ylim()
        if hi_y / lo_y >= 2.5:                 # wide range (p=0.8, 0.95): round values
            cand = (0.5, 0.7, 1, 2, 3, 5, 7, 10)
        else:                                  # narrow range (p=0.5): steps of 0.25
            cand = np.arange(0.25, 10, 0.25)
        ticks = [round(v, 2) for v in cand if lo_y <= v <= hi_y]
        while len(ticks) > 6:
            ticks = ticks[::2]
        axes[0, 0].yaxis.set_major_locator(matplotlib.ticker.FixedLocator(ticks))
        axes[0, 0].yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f'{v:g}'))
        axes[0, 0].yaxis.set_minor_locator(matplotlib.ticker.NullLocator())
        h, lab = axes[0, 0].get_legend_handles_labels()
        fig.legend(h, lab, loc='upper center', bbox_to_anchor=(0.5, 1.0), ncol=len(algs), fontsize=9)
        # fig.suptitle(f'Induction task, p_repeat={p}: final loss vs LR  (line = median of 6 seeds, band = min-max, '
        #              f'★ = best LR, dashed = entropy floor)\n'
        #              f'counts per LR: n× = failed-to-learn seeds (excess loss > {FAIL_GAP:g} of the gap uniform → floor), '
        #              f'n† = diverged seeds', fontsize=10)
        fig.tight_layout()
        fig.subplots_adjust(top=0.92)
        fig.savefig(os.path.join(FIG, f'ind_lr_sweep_p{p}.pdf'))
        fig.savefig(os.path.join(FIG, f'ind_lr_sweep_p{p}.png'), dpi=130)
        plt.close(fig)

    # ---- Fig 2: good-LR windows for every setting (who is within 5% of the floor-gap at which LR)
    labels, mat = [], []
    for ip, p in enumerate(ps):
        for iL, Ly in enumerate(layers):
            for ih, h in enumerate(heads):
                g = med[ip, ih, iL] <= 0.05
                mat.append(g[0] * 1 + g[1] * 2)    # 0 none, 1 AdamW only, 2 Adan only, 3 both
                labels.append(f'p={p} L={Ly} h={h}')
    mat = np.array(mat)
    from matplotlib.colors import ListedColormap
    cmap = ListedColormap(['#f2f2f0', COL['adamw'], COL['adan'], '#555555'])
    fig, ax = plt.subplots(figsize=(6.5, 10))
    ax.imshow(mat, cmap=cmap, vmin=0, vmax=3, aspect='auto')
    ax.set_xticks(range(len(lrs)), [f'{x:g}' for x in lrs], rotation=60)
    ax.set_yticks(range(len(labels)), labels, fontsize=7)
    ax.set_xticks(np.arange(-.5, len(lrs)), minor=True)
    ax.set_yticks(np.arange(-.5, len(labels)), minor=True)
    ax.grid(which='minor', color='white', lw=1.5)
    ax.grid(which='major', visible=False)
    ax.tick_params(which='minor', length=0)
    for k in (12, 24):
        ax.axhline(k - .5, color='black', lw=1)
    from matplotlib.patches import Patch
    ax.legend(handles=[Patch(color='#555555', label='both'), Patch(color=COL['adamw'], label='AdamW only'),
                       Patch(color=COL['adan'], label='Adan only'), Patch(color='#f2f2f0', label='neither')],
              loc='upper center', bbox_to_anchor=(0.5, -0.09), ncol=4, fontsize=8)
    ax.set_xlabel('learning rate')
    ax.set_title('LRs whose median final loss closes ≥95% of the gap\nuniform → entropy floor', fontsize=10)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'ind_good_lr_windows.pdf'))
    fig.savefig(os.path.join(FIG, 'ind_good_lr_windows.png'), dpi=130)
    plt.close(fig)

    # ---- Fig 3: tuning-robustness profile: fraction of the LR grid within tolerance tau of the floor
    taus = np.logspace(-3, 0, 60)
    fig, ax = plt.subplots(figsize=(5, 3.6))
    for ia, alg in enumerate(algs):
        frac = [(med[..., ia, :] <= t).mean() for t in taus]
        ax.plot(taus, frac, color=COL[alg], lw=2, label=NAME[alg])
    ax.set_xscale('log')
    ax.set_xlabel('tolerance: normalised excess loss over floor')
    ax.set_ylabel('fraction of LR grid that succeeds')
    ax.set_title('Induction: how forgiving is the LR choice?\n(all 36 settings pooled)', fontsize=10)
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, 'ind_robustness_profile.pdf'))
    fig.savefig(os.path.join(FIG, 'ind_robustness_profile.png'), dpi=130)
    plt.close(fig)


